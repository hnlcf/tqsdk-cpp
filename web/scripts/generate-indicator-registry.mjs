#!/usr/bin/env node
// Scan public/plugins/*/manifest.json and generate the runtime registry.
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const root = new URL("..", import.meta.url).pathname;
const pluginsRoot = join(root, "public/plugins");
const output = join(root, "src/indicators/wasm/registry.generated.ts");

const plugins = [];
for (const entry of readdirSync(pluginsRoot, { withFileTypes: true })) {
  if (!entry.isDirectory()) continue;
  const manifestPath = join(pluginsRoot, entry.name, "manifest.json");
  let manifest;
  try {
    manifest = JSON.parse(readFileSync(manifestPath, "utf8"));
  } catch (error) {
    throw new Error(`${manifestPath}: cannot parse manifest: ${error}`);
  }
  if (typeof manifest.id !== "string" || !manifest.id) {
    throw new Error(`${manifestPath}: missing id`);
  }
  if (manifest.id !== entry.name) {
    throw new Error(`${manifestPath}: id must match directory name`);
  }
  plugins.push({
    id: manifest.id,
    name: typeof manifest.name === "string" ? manifest.name : manifest.id,
    version: typeof manifest.version === "string" ? manifest.version : "0.0.0",
    manifestUrl: `/plugins/${entry.name}/manifest.json`,
    defaultEnabled: manifest.defaultEnabled === true,
    order: typeof manifest.order === "number" ? manifest.order : 1000,
  });
}

if (plugins.length === 0) {
  throw new Error(`no indicator manifests found under ${pluginsRoot}`);
}
plugins.sort((a, b) => a.order - b.order || a.id.localeCompare(b.id));
const ids = new Set();
for (const plugin of plugins) {
  if (ids.has(plugin.id)) throw new Error(`duplicate plugin id: ${plugin.id}`);
  ids.add(plugin.id);
}

const rows = plugins
  .map(
    (plugin) =>
      `  { id: ${JSON.stringify(plugin.id)}, name: ${JSON.stringify(plugin.name)}, ` +
      `version: ${JSON.stringify(plugin.version)}, manifestUrl: ${JSON.stringify(plugin.manifestUrl)}, ` +
      `defaultEnabled: ${plugin.defaultEnabled} },`,
  )
  .join("\n");
const content = `// Generated by web/scripts/generate-indicator-registry.mjs. Do not edit.\n` +
  `export const WASM_PLUGIN_REGISTRY = [\n${rows}\n] as const;\n`;
writeFileSync(output, content);
console.log(`generated ${output} (${plugins.length} plugins)`);
