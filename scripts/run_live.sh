#!/usr/bin/env bash
#
# 启动 Tq 行情 + CTP 交易的 gw/node 后端。
#
# 默认读取 config/live.local.env（已加入 .gitignore）；可复制
# config/live.local.env.example 后填写自己的 CTP 账号。
#
# 用法:
#   ./scripts/run_live.sh                 # 启动 gw/node（build-ui）
#   ./scripts/run_live.sh --build         # 先构建 gw/node
#   ./scripts/run_live.sh --no-ui         # 兼容参数，等价于默认行为
#   ./scripts/run_live.sh --help
#
# Web UI 请用 ./scripts/run_web.sh；退出时按 node -> gw 清理。

set -Eeuo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
BUILD_DIR="${TQSDK_BUILD_DIR:-$ROOT/build-ui}"
CONFIG_FILE="${TQSDK_LIVE_CONFIG:-$ROOT/config/live.local.env}"
RUN_DIR="${TQSDK_RUN_DIR:-$ROOT/run/live}"
BUILD_REQUESTED=0
CLI_GW_PORT=""
CLI_HTTP_PORT=""
CLI_SYMBOLS=""

usage() {
    sed -n '2,14p' "$0" | sed 's/^# \{0,1\}//'
}

while [[ $# -gt 0 ]]; do
    case "$1" in
    --build)
        BUILD_REQUESTED=1
        shift
        ;;
    --no-ui)
        shift
        ;;
    --config)
        CONFIG_FILE="${2:?--config requires a path}"
        shift 2
        ;;
    --build-dir)
        BUILD_DIR="${2:?--build-dir requires a path}"
        shift 2
        ;;
    --gw-port)
        CLI_GW_PORT="${2:?--gw-port requires a number}"
        shift 2
        ;;
    --http-port)
        CLI_HTTP_PORT="${2:?--http-port requires a number}"
        shift 2
        ;;
    --symbols)
        CLI_SYMBOLS="${2:?--symbols requires comma-separated symbols}"
        shift 2
        ;;
    -h|--help)
        usage
        exit 0
        ;;
    *)
        echo "unknown argument: $1" >&2
        usage >&2
        exit 2
        ;;
    esac
done

# 默认值；local env 可以覆盖它们。
GW_PORT=14330
HTTP_PORT=18081
TQ_MD_HOST="free-openmd.shinnytech.com"
TQ_MD_PORT="443"
TQ_MD_PATH="/t/md/front/mobile"
CTP_BROKER_ID="9999"
CTP_USER_ID=""
CTP_PASSWORD=""
CTP_AUTH_CODE="0000000000000000"
CTP_APP_ID="simnow_client_test"
CTP_TD_FRONT="tcp://182.254.243.31:30001"
CTP_MD_FRONT="tcp://182.254.243.31:30012"
SYMBOLS="SHFE.rb2701"
INSTRUMENTS_FILE="$ROOT/symbol.json"
FLOW_PATH=""

if [[ -f "$CONFIG_FILE" ]]; then
    # shellcheck disable=SC1090
    set -a
    source "$CONFIG_FILE"
    set +a
fi

if [[ -n "$CLI_GW_PORT" ]]; then
    GW_PORT="$CLI_GW_PORT"
fi
if [[ -n "$CLI_HTTP_PORT" ]]; then
    HTTP_PORT="$CLI_HTTP_PORT"
fi
if [[ -n "$CLI_SYMBOLS" ]]; then
    SYMBOLS="$CLI_SYMBOLS"
fi

if [[ -z "$CTP_USER_ID" || -z "$CTP_PASSWORD" ]]; then
    cat >&2 <<EOF
缺少 CTP 账号配置。

请创建 $CONFIG_FILE，内容参考：

  cp config/live.local.env.example config/live.local.env
  chmod 600 config/live.local.env
  \$EDITOR config/live.local.env

或者直接导出 CTP_USER_ID / CTP_PASSWORD / CTP_BROKER_ID /
CTP_TD_FRONT / CTP_MD_FRONT 等环境变量。
EOF
    exit 1
fi

case "$GW_PORT:$HTTP_PORT" in
    *[!0-9:]*)
        echo "端口必须是数字: GW_PORT=$GW_PORT HTTP_PORT=$HTTP_PORT" >&2
        exit 2
        ;;
esac

if [[ -z "$FLOW_PATH" ]]; then
    FLOW_PATH="$RUN_DIR/ctp-flow"
fi
mkdir -p "$RUN_DIR" "$RUN_DIR/logs" "$FLOW_PATH"

GW_BIN="${TQSDK_GW_BIN:-$BUILD_DIR/tqsdk-gw}"
NODE_BIN="${TQSDK_NODE_BIN:-$BUILD_DIR/tqsdk-node}"
GW_CONFIG="$RUN_DIR/gw.toml"
NODE_CONFIG="$RUN_DIR/node.toml"
GW_LOG="$RUN_DIR/logs/gw.log"
NODE_LOG="$RUN_DIR/logs/node.log"

if [[ "$BUILD_REQUESTED" == "1" || ! -x "$GW_BIN" || ! -x "$NODE_BIN" ]]; then
    if [[ ! -f "$BUILD_DIR/CMakeCache.txt" ]]; then
        cat >&2 <<EOF
找不到构建目录: $BUILD_DIR

先执行:
  export VCPKG_ROOT=/path/to/vcpkg
  cmake --preset ui-dev
  cmake --build --preset ui-dev
EOF
        exit 1
    fi
    if ! grep -Eq '^TQSDK_ENABLE_CTP:BOOL=ON$' "$BUILD_DIR/CMakeCache.txt"; then
        echo "构建目录未开启 TQSDK_ENABLE_CTP: $BUILD_DIR" >&2
        exit 1
    fi
    echo "构建 tqsdk-gw / tqsdk-node ..."
    cmake --build "$BUILD_DIR" --target tqsdk-gw tqsdk-node -j
fi

if ! grep -Eq '^TQSDK_ENABLE_CTP:BOOL=ON$' "$BUILD_DIR/CMakeCache.txt"; then
    echo "警告: $BUILD_DIR 不是 TQSDK_ENABLE_CTP=ON 构建，CTP td 可能不可用。" >&2
fi

# 用 Python 写 TOML，避免手工拼接字符串/数组时出现引号问题。
export GW_PORT HTTP_PORT TQ_MD_HOST TQ_MD_PORT TQ_MD_PATH
export CTP_BROKER_ID CTP_USER_ID CTP_PASSWORD CTP_AUTH_CODE CTP_APP_ID
export CTP_TD_FRONT CTP_MD_FRONT SYMBOLS INSTRUMENTS_FILE FLOW_PATH
python3 - "$GW_CONFIG" "$NODE_CONFIG" "$RUN_DIR" <<'PY'
import json
import os
import sys

gw_path, node_path, run_dir = sys.argv[1:]

def q(name):
    return json.dumps(os.environ.get(name, ""))

symbols = [item.strip() for item in os.environ.get("SYMBOLS", "").split(",") if item.strip()]
symbols_toml = "[" + ", ".join(json.dumps(item) for item in symbols) + "]"

gw = f"""# generated by scripts/run_live.sh
[listen]
transport = "tcp"
tcp_host = "127.0.0.1"
tcp_port = {int(os.environ["GW_PORT"])}

[ipc]
encoding = "json"
handshake_timeout_ms = 5000
heartbeat_interval_ms = 1000
heartbeat_timeout_ms = 10000
local_name = "gw-live-tq-ctp"

[md]
kind = "tq"
host = {q("TQ_MD_HOST")}
port = {q("TQ_MD_PORT")}
path = {q("TQ_MD_PATH")}

[td]
kind = "ctp"

[ctp]
broker_id = {q("CTP_BROKER_ID")}
user_id = {q("CTP_USER_ID")}
password = {q("CTP_PASSWORD")}
auth_code = {q("CTP_AUTH_CODE")}
app_id = {q("CTP_APP_ID")}
td_front = {q("CTP_TD_FRONT")}
md_front = {q("CTP_MD_FRONT")}
flow_path = {q("FLOW_PATH")}
order_interval_ms = 100

[runtime]
threads = 2
"""

node = f"""# generated by scripts/run_live.sh
[ipc]
transport = "tcp"
encoding = "json"
handshake_timeout_ms = 5000
heartbeat_interval_ms = 1000
heartbeat_timeout_ms = 10000
local_name = "node-live-tq-ctp"

[md]
kind = "remote"
tcp_host = "127.0.0.1"
tcp_port = {int(os.environ["GW_PORT"])}

[td]
kind = "remote"
tcp_host = "127.0.0.1"
tcp_port = {int(os.environ["GW_PORT"])}
ack_timeout_ms = 10000

[serve]
bind = "127.0.0.1"
port = {int(os.environ["HTTP_PORT"])}
symbols = {symbols_toml}

[serve.ws]
path = "/stream"
heartbeat_interval_ms = 30000
max_clients = 256
max_queue = 1024
coalesce_ms = 10

[instruments]
enabled = true
file = {q("INSTRUMENTS_FILE")}
refresh_interval_sec = 21600
initial_delay_sec = 60

[kline_cache]
enabled = true
file = {json.dumps(os.path.join(run_dir, "kline_cache.sqlite3"))}
max_bars_per_series = 2000
flush_interval_ms = 250
max_pending_bars = 50000
fresh_after_sec = 900

[runtime]
threads = 4
"""

with open(gw_path, "w", encoding="utf-8") as stream:
    stream.write(gw)
with open(node_path, "w", encoding="utf-8") as stream:
    stream.write(node)
PY

port_in_use() {
    python3 - "$1" "$2" <<'PY'
import socket
import sys
try:
    with socket.create_connection((sys.argv[1], int(sys.argv[2])), timeout=0.4):
        sys.exit(0)
except OSError:
    sys.exit(1)
PY
}

wait_tcp() {
    python3 - "$1" "$2" "$3" <<'PY'
import socket
import sys
import time
host, port, timeout = sys.argv[1], int(sys.argv[2]), float(sys.argv[3])
deadline = time.monotonic() + timeout
while time.monotonic() < deadline:
    try:
        with socket.create_connection((host, port), timeout=0.4):
            sys.exit(0)
    except OSError:
        time.sleep(0.2)
sys.exit(1)
PY
}

if port_in_use 127.0.0.1 "$GW_PORT"; then
    echo "端口 $GW_PORT 已被占用，停止后重试，或用 --gw-port 指定其它端口。" >&2
    exit 1
fi
if port_in_use 127.0.0.1 "$HTTP_PORT"; then
    echo "端口 $HTTP_PORT 已被占用，停止后重试，或用 --http-port 指定其它端口。" >&2
    exit 1
fi

GW_PID=""
NODE_PID=""
cleanup() {
    trap - EXIT INT TERM
    set +e
    echo
    echo "停止 gw/node ..."
    for pid in "$NODE_PID" "$GW_PID"; do
        if [[ -n "$pid" ]]; then
            kill -TERM "$pid" 2>/dev/null || true
        fi
    done
    sleep 1
    for pid in "$NODE_PID" "$GW_PID"; do
        if [[ -n "$pid" ]]; then
            kill -KILL "$pid" 2>/dev/null || true
        fi
    done
    wait 2>/dev/null || true
    echo "日志: $RUN_DIR/logs/"
}
trap cleanup EXIT
trap 'exit 130' INT TERM

start_gw() {
    echo "启动 gw (Tq md + CTP td) ..."
    export TQSDK_LOG_LEVEL="${TQSDK_LOG_LEVEL:-info}"
    "$GW_BIN" -c "$GW_CONFIG" >"$GW_LOG" 2>&1 &
    GW_PID=$!
    if ! wait_tcp 127.0.0.1 "$GW_PORT" 20; then
        echo "gw 未在 20s 内监听 :$GW_PORT，日志如下：" >&2
        tail -80 "$GW_LOG" >&2 || true
        exit 1
    fi
}

start_node() {
    echo "启动 node (HTTP :$HTTP_PORT) ..."
    "$NODE_BIN" -c "$NODE_CONFIG" >"$NODE_LOG" 2>&1 &
    NODE_PID=$!
    if ! wait_tcp 127.0.0.1 "$HTTP_PORT" 25; then
        echo "node 未在 25s 内监听 :$HTTP_PORT，日志如下：" >&2
        tail -80 "$NODE_LOG" >&2 || true
        exit 1
    fi

    if command -v curl >/dev/null 2>&1; then
        local ready=0
        for _ in $(seq 1 40); do
            if [[ "$(curl -s -o /dev/null -w '%{http_code}' --max-time 1 \
                "http://127.0.0.1:$HTTP_PORT/readyz" || true)" == "200" ]]; then
                ready=1
                break
            fi
            sleep 1
        done
        if [[ "$ready" == "1" ]]; then
            echo "node 已就绪: http://127.0.0.1:$HTTP_PORT"
        else
            echo "注意: /readyz 仍未返回 200；CTP 登录/行情可能较慢。" >&2
            echo "      可查看 $NODE_LOG 或 $GW_LOG。" >&2
        fi
    fi
}

start_gw
start_node

cat <<EOF

运行中:
  gw:   tcp://127.0.0.1:$GW_PORT
  node: http://127.0.0.1:$HTTP_PORT  (ws /stream)
  web:  ./scripts/run_web.sh  (http://127.0.0.1:5173)
  日志: $RUN_DIR/logs/
  合约: $SYMBOLS

常用检查:
  curl -s http://127.0.0.1:$HTTP_PORT/readyz
  curl -s http://127.0.0.1:$HTTP_PORT/quote/SHFE.rb2701
  curl -s http://127.0.0.1:$HTTP_PORT/account

Web UI 请另开终端运行 ./scripts/run_web.sh。按 Ctrl-C 结束 gw/node。
EOF

while true; do
    if ! kill -0 "$GW_PID" 2>/dev/null; then
        echo "gw 已退出，开始清理；请查看 $GW_LOG。" >&2
        exit 1
    fi
    if ! kill -0 "$NODE_PID" 2>/dev/null; then
        echo "node 已退出，开始清理；请查看 $NODE_LOG。" >&2
        exit 1
    fi
    sleep 1
done
